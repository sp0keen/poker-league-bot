// очки за место — фиксированная таблица на 4-10 игроков: 1-е место = N + 2, предпоследнее 0,
// последнее -1; промежуточные места — round((N + 2) * r^1.3), r = (N - 1 - место) / (N - 2),
// так что верх лестницы ценится сильнее низа; соседние места различаются минимум на 1 очко
const PLACEMENT_POINTS = {
  4: [6, 2, 0, -1],
  5: [7, 4, 2, 0, -1],
  6: [8, 6, 3, 1, 0, -1],
  7: [9, 7, 5, 3, 1, 0, -1],
  8: [10, 8, 6, 4, 2, 1, 0, -1],
  9: [11, 9, 7, 5, 4, 2, 1, 0, -1],
  10: [12, 10, 8, 7, 5, 3, 2, 1, 0, -1]
};

function placementPoints(place, N) {
  return PLACEMENT_POINTS[N][place - 1];
}

module.exports = { placementPoints, PLACEMENT_POINTS };
